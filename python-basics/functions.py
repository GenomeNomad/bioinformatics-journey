def say_hello(name, age):
    print("Hello " + name + " you are " + age)
say_hello("Ryan", "25")
say_hello("Peter", "21")

def say_hello_there(name):
    print("Hello there " + name + ", what's up?" )
say_hello_there("Aakash")

def say_hi(name, age):
    print("Hi " + name + ", you are " + str(age))
say_hi("Harry", 30)
say_hi("Norman", 40)

def cube(num):
    return num*num*num
print(cube(5))

def square(num):
    return num*num
result = square(5)
print(result)
