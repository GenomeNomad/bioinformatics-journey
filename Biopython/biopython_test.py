from Bio.Seq import Seq
dna= Seq("ATGAAACCCGGGTTT")
print(dna)
print(dna.complement())
print(dna.reverse_complement())
print(dna.count("A"))
print(dna.count("C"))
print(dna.count("G"))
print(dna.count("T"))
rna=dna.transcribe()
print(rna)
protein=dna.translate()
print(protein)

